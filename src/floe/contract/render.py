"""Business-owned entity YAML and the fail-closed `_domain.yml` scaffold.

Pure except `plan_first_import`, which only checks which files already exist.
"""

import hashlib
import json
import os
from collections.abc import Mapping, Sequence
from typing import Any, cast

from floe.add_entity import _render  # pyright: ignore[reportPrivateUsage] -- the one deterministic YAML emitter
from floe.contract.checks import compile_checks
from floe.contract.publish import PlannedFile
from floe.contract.schema import compile_schema
from floe.contract.workbook import ColumnRow, TableRow

# the key paths the importer owns (#1449 "Ownership"); everything else is the engineer's
_OWNED = (
    ("name",),
    ("domain",),
    ("metadata", "owner"),
    ("metadata", "description"),
    ("source", "resource"),
    ("policy", "severity"),
    ("policy", "rule_severity"),
    ("schema", "columns"),
    ("schema", "primary_key"),
    ("schema", "unique_keys"),
)
_SCAFFOLD = """\
# Engineer-owned. floe contract import created this file once and never changes it.
name: {domain}
defaults:
  source:
    ref: TODO_source              # declare it in sources, or use format + path with {{{{resource}}}}
  sink:
    accepted:
      format: TODO_format
      path: "{{{{TODO_accepted_path}}}}"
    rejected:
      format: TODO_format
      path: "{{{{TODO_rejected_path}}}}"
"""


def owned(entity: Mapping[Any, Any]) -> dict[str, Any]:
    """The projection of `entity` onto the importer's key paths."""
    out: dict[str, Any] = {}
    for path in _OWNED:
        node: Any = entity
        for key in path:
            node = (
                cast("Mapping[str, Any]", node).get(key)
                if isinstance(node, Mapping)
                else None
            )
        if node is not None:
            target = out
            for key in path[:-1]:
                target = target.setdefault(key, {})
            target[path[-1]] = node
    return out


def fingerprint(projection: Mapping[str, Any]) -> str:
    text = json.dumps(projection, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(text.encode()).hexdigest()


def build_entity(
    domain: str,
    table: TableRow,
    columns: Sequence[ColumnRow],
    default_severity: str,
    errors: list[str],
) -> dict[str, Any]:
    """`compile_schema` plus `compile_checks`: policy and each column's check keys merged in."""
    entity = compile_schema(domain, table, list(columns), errors)
    checks = compile_checks(table, columns, default_severity, errors)
    schema = entity.pop("schema")
    schema["columns"] = [
        {**c, **checks["columns"].get(c["name"], {})} for c in schema["columns"]
    ]
    return {**entity, "policy": checks["policy"], "schema": schema}


def _line(text: str) -> str:
    return " ".join(text.split())


def render_entity(
    entity: Mapping[str, Any], table: TableRow, columns: Sequence[ColumnRow]
) -> str:
    """Header comments, then the entity as YAML: byte-deterministic."""
    keys = [".".join(p) for p in _OWNED]
    header = [
        f"# floe-contract: sha256:{fingerprint(owned(entity))}",
        "# Generated by floe contract import. Business-owned keys (edit them in the workbook): "
        + ", ".join(keys),
    ]
    for label, value in (
        ("business_name", table.business_name),
        ("grain", table.grain),
    ):
        if value and value.strip():
            header.append(f"# {label}: {_line(value)}")
    for c in columns:
        if c.target_table == table.target_table and c.fk_target_table:
            target = f"{c.fk_target_table}.{c.fk_target_column or ''}".rstrip(".")
            header.append(f"# {c.target_column} → {_line(target)}")
    return "\n".join(header) + "\n" + _render(dict(entity))


def render_domain_scaffold(domain: str) -> str:
    return _SCAFFOLD.format(domain=domain)


def plan_first_import(
    output_dir: str, domain: str, entities: Mapping[str, str]
) -> list[PlannedFile]:
    """`created` entries (paths relative to `output_dir`) for each absent file."""
    files = {"_domain.yml": render_domain_scaffold(domain)}
    files.update({f"{name}.yml": text for name, text in entities.items()})
    return [
        PlannedFile(path, None, text, "created")
        for path, text in files.items()
        if not os.path.exists(os.path.join(output_dir, path))
    ]
