from __future__ import annotations

import json
from pathlib import Path
import tempfile
import unittest

import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from airflow_floe.manifest import (  # noqa: E402
    AirflowManifest,
    load_manifest,
)
from airflow_floe.runtime import build_dag_manifest_context  # noqa: E402

FIXTURES = Path(__file__).resolve().parent / "fixtures"


class ManifestLoaderTests(unittest.TestCase):
    def _manifest_payload(self) -> dict:
        return {
            "spec_version": "0.8",
            "floe_version": "0.8.0",
            "generated_at_ts_ms": 1739500000000,
            "config_uri": "./example/config.yml",
            "config_checksum": "abc123",
            "execution": {
                "entrypoint": "floe",
                "base_args": ["run", "-c", "{config_uri}", "--log-format", "json", "--quiet"],
                "per_entity_args": ["--entities", "{entity_name}"],
                "log_format": "json",
                "result_contract": {
                    "run_finished_event": True,
                    "summary_uri_field": "summary_uri",
                    "exit_codes": {
                        "0": "success_or_rejected",
                        "1": "technical_failure",
                        "2": "aborted",
                    },
                },
                "defaults": {"env": {}, "workdir": None},
            },
            "runners": {
                "default": "local",
                "definitions": {
                    "local": {
                        "type": "local_process",
                        "image": None,
                        "namespace": None,
                        "service_account": None,
                        "resources": None,
                        "env": None,
                        "command": None,
                        "args": None,
                        "timeout_seconds": None,
                        "ttl_seconds_after_finished": None,
                        "poll_interval_seconds": None,
                        "secrets": None,
                    }
                },
            },
            "entities": [
                {
                    "name": "employees",
                    "domain": "hr",
                    "group_name": "hr",
                    "source_format": "csv",
                    "accepted_sink_uri": "./out/accepted/employees",
                    "rejected_sink_uri": "./out/rejected/employees",
                    "asset_key": ["hr", "employees"],
                    "runner": None,
                },
                {
                    "name": "orders",
                    "domain": None,
                    "group_name": "floe",
                    "source_format": "csv",
                    "accepted_sink_uri": "./out/accepted/orders",
                    "rejected_sink_uri": None,
                    "asset_key": ["orders"],
                    "runner": None,
                },
            ],
        }

    def test_load_manifest_from_native_manifest_schema(self) -> None:
        payload = self._manifest_payload()

        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "manifest.json"
            target.write_text(json.dumps(payload), encoding="utf-8")

            loaded = load_manifest(target)
            self.assertIsInstance(loaded, AirflowManifest)
            self.assertEqual(loaded.spec_version, "0.8")
            self.assertEqual(loaded.config_uri, "./example/config.yml")
            self.assertEqual(len(loaded.entities), 2)
            self.assertEqual(loaded.entities[0].name, "employees")

    def test_python_core_0_8_manifest_builds_dag_context(self) -> None:
        # Generated by `floe manifest generate -c conformance/manifest_run/config.yml`.
        context = build_dag_manifest_context(str(FIXTURES / "manifest_0_8.json"))

        self.assertEqual(context.entity_names, ["finance.orders", "sales.orders"])
        self.assertEqual(context.manifest.spec_version, "0.8")
        self.assertEqual(
            context.config_path, "/srv/floe/manifest_run/config.yml"
        )

    def test_load_manifest_rejects_unsupported_spec_version(self) -> None:
        payload = self._manifest_payload()
        payload["spec_version"] = "0.7"

        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "manifest-0.7.json"
            target.write_text(json.dumps(payload), encoding="utf-8")

            with self.assertRaisesRegex(
                ValueError, r"manifest spec_version 0\.7 is not supported \(supported: 0\.8\)"
            ):
                load_manifest(target)

    def test_load_manifest_accepts_databricks_runner_contract(self) -> None:
        payload = self._manifest_payload()
        payload["runners"] = {
            "default": "dbx",
            "definitions": {
                "dbx": {
                    "type": "databricks_job",
                    "workspace_url": "https://adb-1234.5.azuredatabricks.net",
                    "existing_cluster_id": "1111-222222-abc123",
                    "config_uri": "dbfs:/floe/configs/prod.yml",
                    "python_file_uri": "dbfs:/floe/bin/floe_entry.py",
                    "job_name": "floe-sales-prod",
                    "command": "floe",
                    "args": ["run", "-c", "dbfs:/floe/configs/prod.yml"],
                    "poll_interval_seconds": 20,
                    "timeout_seconds": 1800,
                    "auth": {
                        "service_principal_oauth_ref": "env://DATABRICKS_TOKEN"
                    },
                    "env_parameters": {"FLOE_ENV": "prod"},
                }
            },
        }

        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "manifest.dbx.json"
            target.write_text(json.dumps(payload), encoding="utf-8")

            loaded = load_manifest(target)
            runner = loaded.runners.definitions["dbx"]
            self.assertEqual(runner.runner_type, "databricks_job")
            self.assertEqual(runner.workspace_url, "https://adb-1234.5.azuredatabricks.net")
            self.assertEqual(runner.command, ["floe"])


if __name__ == "__main__":
    unittest.main()
